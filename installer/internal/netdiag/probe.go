// Probe is every effect the diagnosis has, one function per effect, so that a
// test can run the whole package against simulated resolvers, sockets, HTTP
// servers, files and programs. Nothing in this package opens a socket, reads a
// file or starts a process except through these fields.
//
// The zero Probe is not usable: a caller takes DefaultProbe and replaces what it
// needs.
type Probe struct {
	// GOOS is the operating system the checks are running on ("linux", "darwin",
	// ...). It selects the platform's own way of reading the route table and the
	// resolver configuration.
	GOOS string
	// WSL reports that this run is inside WSL, where the resolver configuration is
	// generated by the Windows host and the interfaces are virtual. It changes
	// what the report says about a difference, never what it dials.
	WSL bool

	// Getenv reads one environment variable.
	Getenv func(string) string
	// Environ lists the environment, which is what the proxy check walks.
	Environ func() []string
	// LookPath answers whether a program exists, and where. It is what gates the
	// checks that need a binary: a platform without the tool reports the check as
	// skipped and everything else still runs.
	LookPath func(string) (string, error)
	// ReadFile reads a file, for /etc/resolv.conf, /proc/net/route and
	// /etc/wsl.conf. A missing file is an error the check turns into a reason.
	ReadFile func(string) ([]byte, error)

	// Interfaces lists the network interfaces and InterfaceAddrs their addresses.
	Interfaces     func() ([]net.Interface, error)
	InterfaceAddrs func(net.Interface) ([]net.Addr, error)
	// Hostname is this machine's name, used for the context lines of the report.
	Hostname func() (string, error)
	// Now is the clock the run measures with.
	Now func() time.Time

	// NewResolver builds a resolver: the system resolver when server is empty,
	// and a Go resolver that asks that one server otherwise. Querying a configured
	// server directly is what lets the report name the server that answered.
	NewResolver func(server string) *net.Resolver
	// LookupHost resolves a name with a resolver. It is separate from NewResolver
	// so a test can answer without a resolver at all.
	LookupHost func(ctx context.Context, r *net.Resolver, host string) ([]string, error)

	// DialContext opens a TCP connection. The context carries the bound, so a
	// dial that does not answer is cancelled rather than waited on.
	DialContext func(ctx context.Context, network, address string) (net.Conn, error)
	// HTTPClient builds the client the HTTP check uses. Proxy comes from the
	// machine's own environment, the redirect limit and the timeouts come from
	// the bounds, and the client is never built to skip verification: there is no
	// parameter here that could ask for it.
	HTTPClient func(b Bounds) *http.Client
	// TLSHandshake performs a verified handshake and returns the negotiated
	// state, or the verification error. It never sets InsecureSkipVerify.
	TLSHandshake func(ctx context.Context, address, serverName string) (tls.ConnectionState, error)

	// ExecOutput runs one program with explicit arguments and returns its output.
	// The arguments are passed as they are: no shell is ever involved, so nothing
	// a user typed can become a command. A missing program is an error the check
	// turns into a reason.
	ExecOutput func(ctx context.Context, name string, args ...string) ([]byte, error)
}

// DefaultProbe is the real thing: the operating system, the network and the
// programs of the machine this runs on.
func DefaultProbe() Probe {
	return Probe{
		GOOS:           runtime.GOOS,
		WSL:            detectWSL(),
		Getenv:         os.Getenv,
		Environ:        os.Environ,
		LookPath:       exec.LookPath,
		ReadFile:       os.ReadFile,
		Interfaces:     net.Interfaces,
		InterfaceAddrs: func(i net.Interface) ([]net.Addr, error) { return i.Addrs() },
		Hostname:       os.Hostname,
		Now:            time.Now,
		NewResolver:    defaultResolver,
		LookupHost: func(ctx context.Context, r *net.Resolver, host string) ([]string, error) {
			return r.LookupHost(ctx, host)
		},
		DialContext: func(ctx context.Context, network, address string) (net.Conn, error) {
			var d net.Dialer
			return d.DialContext(ctx, network, address)
		},
		HTTPClient:   defaultHTTPClient,
		TLSHandshake: defaultTLSHandshake,
		ExecOutput:   defaultExecOutput,
	}
}

// detectWSL answers whether this process runs inside WSL, from the variables WSL
// sets and the kernel string it presents. It is the default for Probe.WSL; a
// caller that has already detected the platform passes its own answer instead.
func detectWSL() bool {
	if os.Getenv("WSL_DISTRO_NAME") != "" || os.Getenv("WSL_INTEROP") != "" {
		return true
	}
	version, err := os.ReadFile("/proc/version")
	if err != nil {
		return false
	}
	return strings.Contains(strings.ToLower(string(version)), "microsoft")
}

// defaultResolver builds the resolver a DNS check uses. An empty server is the
// system resolver, which is what an application would use; a named server is
// queried directly with the Go resolver, which is how the report can name the
// server that answered and how long it took.
func defaultResolver(server string) *net.Resolver {
	if server == "" {
		return net.DefaultResolver
	}
	address := server
	if _, _, err := net.SplitHostPort(address); err != nil {
		address = net.JoinHostPort(server, "53")
	}
	return &net.Resolver{
		PreferGo: true,
		Dial: func(ctx context.Context, network, _ string) (net.Conn, error) {
			var d net.Dialer
			return d.DialContext(ctx, network, address)
		},
	}
}

// defaultHTTPClient builds the HTTP client from the bounds: the machine's own
// proxy configuration, the redirect limit, the timeouts and the response header
// bound. Verification is not a parameter here on purpose: a caller cannot ask
// this utility to trust a certificate it should not.
func defaultHTTPClient(b Bounds) *http.Client {
	return &http.Client{
		Transport: &http.Transport{
			Proxy:                 http.ProxyFromEnvironment,
			DialContext:           (&net.Dialer{Timeout: b.tcp()}).DialContext,
			TLSHandshakeTimeout:   b.tls(),
			ResponseHeaderTimeout: b.http(),
			ExpectContinueTimeout: time.Second,
			ForceAttemptHTTP2:     true,
		},
		Timeout: b.http(),
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			if len(via) >= b.redirects() {
				// The limit is a result to report, not a failure: the chain is cut
				// and the last response is handed back with its status.
				return http.ErrUseLastResponse
			}
			return nil
		},
	}
}

// defaultTLSHandshake performs a verified handshake. It follows the platform's
// own minimum protocol version -- it sets no minimum of its own -- and returns
// the connection state even when verification failed, so the report can show
// which certificate was presented and why it was refused.
func defaultTLSHandshake(ctx context.Context, address, serverName string) (tls.ConnectionState, error) {
	var d net.Dialer
	conn, err := d.DialContext(ctx, "tcp", address)
	if err != nil {
		return tls.ConnectionState{}, err
	}
	defer conn.Close()
	if deadline, ok := ctx.Deadline(); ok {
		_ = conn.SetDeadline(deadline)
	}
	tlsConn := tls.Client(conn, &tls.Config{ServerName: serverName})
	if err := tlsConn.HandshakeContext(ctx); err != nil {
		return tlsConn.ConnectionState(), err
	}
	return tlsConn.ConnectionState(), nil
}

// defaultExecOutput runs one program with a bound on its output and its life.
// WaitDelay pairs with the context deadline so a program that leaves a child
// behind holding the output pipe cannot outlive the bound.
func defaultExecOutput(ctx context.Context, name string, args ...string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.WaitDelay = time.Second
	return cmd.Output()
}

// Bounds are the limits every check runs under. They are all positive by
// default and a zero field means the default, never "no limit": an unbounded
// check is exactly the hang this utility exists to avoid, so an Options built
// without bounds is still bounded.
type Bounds struct {
	// DNS bounds one resolution through the system resolver, and DNSServer one
	// query to one configured server.
	DNS       time.Duration
	DNSServer time.Duration
	// TCP bounds one connection attempt, TLS one handshake, HTTP one request, and
	// Trace the whole traceroute.
	TCP   time.Duration
	TLS   time.Duration
	HTTP  time.Duration
	Trace time.Duration
	// Total bounds a whole run. The runner makes one context out of it, so a run
	// cannot outlive the screen's own patience.
	Total time.Duration
	// Attempts is how many addresses one TCP check tries before it reports the
	// failure of the last one.
	Attempts int
	// Redirects is how many redirects the HTTP check follows before it stops and
	// reports the chain it saw.
	Redirects int
	// BodyBytes is how many bytes of a response body the HTTP check reads. It is
	// enough to recognise a portal page and far too little to pull a payload.
	BodyBytes int64
	// There is deliberately no concurrency field. One check runs at a time (see
	// run.go), which is the strongest bound this utility can promise, and a field a
	// caller could raise would promise a parallelism that does not exist.
}

// defaultBounds is the bound every check falls back to for a field the caller
// left at zero.
var defaultBounds = Bounds{
	DNS:       5 * time.Second,
	DNSServer: 3 * time.Second,
	TCP:       5 * time.Second,
	TLS:       6 * time.Second,
	HTTP:      10 * time.Second,
	Trace:     15 * time.Second,
	Total:     90 * time.Second,
	Attempts:  3,
	Redirects: 5,
	BodyBytes: 64 << 10,
}

// DefaultBounds is the set of limits a run uses when the caller names none.
func DefaultBounds() Bounds { return defaultBounds }

// The accessors below are what the checks call. Every one of them substitutes
// the default for a zero field, which is the guarantee that a caller cannot
// accidentally run an unbounded check.
func (b Bounds) dns() time.Duration       { return atLeast(b.DNS, defaultBounds.DNS) }
func (b Bounds) dnsServer() time.Duration { return atLeast(b.DNSServer, defaultBounds.DNSServer) }
func (b Bounds) tcp() time.Duration       { return atLeast(b.TCP, defaultBounds.TCP) }
func (b Bounds) tls() time.Duration       { return atLeast(b.TLS, defaultBounds.TLS) }
func (b Bounds) http() time.Duration      { return atLeast(b.HTTP, defaultBounds.HTTP) }
func (b Bounds) trace() time.Duration     { return atLeast(b.Trace, defaultBounds.Trace) }
func (b Bounds) total() time.Duration     { return atLeast(b.Total, defaultBounds.Total) }
func (b Bounds) attempts() int            { return atLeastInt(b.Attempts, defaultBounds.Attempts) }
func (b Bounds) redirects() int           { return atLeastInt(b.Redirects, defaultBounds.Redirects) }
func (b Bounds) bodyBytes() int64         { return atLeast64(b.BodyBytes, defaultBounds.BodyBytes) }

// atLeast returns a positive duration, or the fallback when the field is zero or
// negative. Negative is treated like zero because a caller who computed a bound
// wrong must not be able to remove the bound.
func atLeast(value, fallback time.Duration) time.Duration {
	if value <= 0 {
		return fallback
	}
	return value
}

func atLeastInt(value, fallback int) int {
	if value <= 0 {
		return fallback
	}
	return value
}

func atLeast64(value, fallback int64) int64 {
	if value <= 0 {
		return fallback
	}
	return value
}

// Options is what one run was asked for: the target (or the predefined
// destination for an overview), the bounds, and whether the checks that need an
// external program are allowed to run.
type Options struct {
	// Target is the destination the user entered. The zero value asks for the
	// overview of this machine's own connectivity.
	Target Target
	// Destination is the predefined place an overview reaches for. It is named by
	// the caller and printed by the report, so this package contacts no host the
	// screen did not declare. A zero Destination makes every check that needs one
	// report itself as skipped.
	Destination Destination
	// Bounds are the limits. A zero Bounds uses DefaultBounds, field by field.
	Bounds Bounds
	// Trace allows the one check that starts an external program (the system's own
	// traceroute), and only for a target the user entered.
	Trace bool
}

// Session is the run's state carried from check to check: what it was asked for,
// its bounds, and what an earlier check learned. The check functions take it so
// that a signature never has to change when a later check needs one more fact.
type Session struct {
	// Ctx is the run's context. It is cancelled when the user stops the run, so
	// every check derives its own bound from it and a cancelled run stops dialling
	// rather than finishing out of sight. A nil Ctx is context.Background().
	Ctx     context.Context
	Options Options
	Facts   Facts
}

// Context is the run's context, never nil.
func (s Session) Context() context.Context {
	if s.Ctx != nil {
		return s.Ctx
	}
	return context.Background()
}

// WithTimeout derives one check's bound from the run's context, so a check is
// bounded by its own stage timeout and by the run's cancellation at the same
// time.
func (s Session) WithTimeout(d time.Duration) (context.Context, context.CancelFunc) {
	return context.WithTimeout(s.Context(), atLeast(d, time.Second))
}

// Endpoint is the destination this session diagnoses: the user's target when
// there is one, and the predefined destination otherwise. ok is false when
// neither was named, in which case a check that needs a destination reports
// itself as skipped.
func (s Session) Endpoint() (Endpoint, bool) {
	if !s.Options.Target.IsZero() {
		return s.Options.Target.Endpoint(), true
	}
	if !s.Options.Destination.IsZero() {
		return s.Options.Destination.Endpoint(), true
	}
	return Endpoint{}, false
}

// Bounds is the session's bounds, with every unset field already filled in.
func (s Session) Bounds() Bounds { return s.Options.Bounds }

// UserTarget reports whether the run diagnoses something the user typed, which
// is what gates the checks that contact a destination on their behalf.
func (s Session) UserTarget() bool { return !s.Options.Target.IsZero() }
